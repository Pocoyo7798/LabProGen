"""Generate the checked-in data models using LinkML's official Pydantic generator."""

from __future__ import annotations

import argparse
import hashlib
from importlib.metadata import version
from pathlib import Path

import yaml
from linkml.generators.pydanticgen import PydanticGenerator
from linkml_runtime.linkml_model.meta import SchemaDefinition

from labprogen.linkml.loader import _strip_unsupported_metamodel_keys

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SCHEMA = ROOT / "schema" / "action_data_model.yaml"
DEFAULT_OUTPUT = ROOT / "labprogen" / "generated" / "action_data_model.py"


def generate_source(schema_path: Path) -> str:
    """Render official generator output without timestamps or machine paths."""
    source = schema_path.read_bytes()
    # `closed` is a documented project extension, enforced by our validator.
    # Do not change the source schema or any supported LinkML constraints.
    schema = SchemaDefinition(**_strip_unsupported_metamodel_keys(yaml.safe_load(source)))
    code = PydanticGenerator(
        schema,
        base_dir=str(schema_path.resolve().parent),
        metadata=False,
        include_generation_date=False,
        extra_fields="forbid",
    ).serialize()
    header = (
        "# Generated by tools/generate_models.py; DO NOT EDIT.\n"
        f"# Source: {schema_path.name}; SHA256: {hashlib.sha256(source).hexdigest()}\n"
        f"# Generator: LinkML {version('linkml')} (official Pydantic generator).\n"
        "# Derived schema content: CC BY 4.0; see schema/README.md for attribution.\n"
        "# Regenerate: uv run python -m tools.generate_models\n\n"
    )
    result = header + code.rstrip() + "\n"
    compile(result, "<generated-models>", "exec")
    return result


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema", type=Path, default=DEFAULT_SCHEMA)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="Fail if the generated file is missing or stale; write nothing.")
    args = parser.parse_args(argv)
    expected = generate_source(args.schema)
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != expected:
            parser.exit(1, "Generated models are out of date. Run: uv run python -m tools.generate_models\n")
        # Check application bindings only for the application schema. Temporary
        # schema experiments may intentionally remove integration anchors.
        if args.schema.resolve() == DEFAULT_SCHEMA.resolve():
            from labprogen.core.config import validate_schema_references
            errors = validate_schema_references()
            if errors:
                parser.exit(1, "\n".join(errors) + "\n")
        print("Generated models and application schema references are synchronized.")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(expected.encode("utf-8"))
        print(f"Generated {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
